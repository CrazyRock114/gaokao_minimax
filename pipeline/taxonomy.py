def _guard(pat: str) -> str:
    """Append a letter-boundary to bare LaTeX command keywords.

    Without this, the `\\in` rule also matched the prefix of `\\infty` /
    `\\int` / `\\inf`, which silently inflated the 集合 tag to 9,200+ hits.
    A bare control word is stored as regex source `\\\\name` (two backslash
    characters + letters); those get `(?![a-zA-Z])` so the rule can only
    match a complete command name.
    """
    bs = chr(92)
    if len(pat) >= 3 and pat[:2] == bs + bs and pat[2:].isalpha():
        return pat + r"(?![a-zA-Z])"
    return pat


def taxonomy_tree() -> list[dict]:
    tree: dict[str, list[dict]] = {}
    for k in K:
        tree.setdefault(k["chapter"], []).append(k)
    return [
        {"chapter": c, "chapter_cn": CHAPTER_LIST[c],
         "points": [{kk: p[kk] for kk in ("code", "name", "note")} for p in pts]}
        for c, pts in tree.items()
    ]


